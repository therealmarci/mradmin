/** The text for a key; {name} parts are filled from values. */
export function t(key, values = {}) {
  const text = texts[lang][key] ?? texts.en[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (_, name) => values[name] ?? '');
}

/** The text for an API error key. */
export function errorText(error) {
  // value: a number that belongs to the error - as is ({n}) or as a wait in ms ({seconds}, {minutes}).
  const v = Number(error?.value ?? 0);
  return error?.text ?? t('error.' + (error?.key ?? 'server'), { n: v, seconds: Math.max(1, Math.ceil(v / 1000)), minutes: Math.max(1, Math.ceil(v / 60000)) });
}
